#!/usr/bin/env python3
"""Regenerates the source-derived parts of docs/final-architecture from the repository (run from the repository root):
   python3 docs/final-architecture/generated/generate.py
Inputs: services/education-api/prisma/schema.prisma, services/education-api/src/**/*.controller.ts, database/migrations/manifest.json, database/staged-migrations."""
import glob, json, os, re, collections
ROOT = os.getcwd(); OUT = 'docs/final-architecture'

# ---------- API routes
routes = []
for f in sorted(glob.glob('services/education-api/src/**/*.controller.ts', recursive=True)):
    s = open(f, encoding='utf-8').read()
    base = re.search(r'@Controller\((?:"([^"]*)")?\)', s); base = (base.group(1) if base and base.group(1) else '')
    guarded = 'SupabaseAuthGuard' in s or 'DeviceAuthGuard' in s
    for m in re.finditer(r'@(Get|Post|Put|Patch|Delete)\((?:"([^"]*)")?\)', s):
        path = '/'.join(x for x in (base, m.group(2) or '') if x).strip('/')
        routes.append((os.path.basename(f).replace('.controller.ts', ''), m.group(1).upper(), '/api/v1/' + path, 'Bearer (Supabase JWT / device token)' if guarded else 'none/other'))
by = collections.defaultdict(list)
for c, m, p, a in routes: by[c].append((m, p, a))
lines = ['# API contract inventory (generated from the controllers)', '', f'{len(routes)} routes in {len(by)} controllers. Base URL `https://api.skynex.best/api/v1`. Authentication: Supabase JWT in `Authorization: Bearer`; authorization is enforced in the services (organization membership, classroom role, permission codes, system administrator). Generated by `generated/generate.py`; request/response DTOs are in `services/education-api/src/modules/**/dto`.', '']
for c in sorted(by):
    lines += [f'## {c}', '', '| Method | Path | Auth |', '|---|---|---|'] + [f'| {m} | `{p}` | {a} |' for m, p, a in by[c]] + ['']
open(f'{OUT}/generated/api-routes.md', 'w').write('\n'.join(lines))

# ---------- Prisma models
schema = open('services/education-api/prisma/schema.prisma', encoding='utf-8').read()
models = {}
for name, body in re.findall(r'^model (\w+) \{(.*?)^\}', schema, re.M | re.S):
    cols, rels = [], []
    for ln in body.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith('//') or ln.startswith('@@'): continue
        parts = ln.split()
        if len(parts) < 2: continue
        fname, ftype = parts[0], parts[1]
        rel = re.search(r'@relation\(([^)]*)\)', ln)
        base = ftype.rstrip('?[]')
        if base in [n for n, _ in re.findall(r'^model (\w+) \{(.*?)^\}', schema, re.M | re.S)] or rel:
            fk = re.search(r'fields: \[([^\]]*)\]', ln)
            if fk and rel: rels.append((base, [x.strip() for x in fk.group(1).split(',')], ftype.endswith('?')))
            continue
        cols.append((fname, ftype, '@id' in ln, '@unique' in ln))
    models[name] = (cols, rels)
names = set(models)
def domain(n):
    if n.startswith('learning_') or n in ('curriculum_nodes',): return 'learning'
    if n in ('users','memberships','roles','permissions','role_permissions','organizations','user_system_roles','education_school_user_profiles','audit_logs','licenses'): return 'identity'
    if n.startswith(('iot_','robot','control_','classroom_lab','org_ent','device','readiness','safety','session_arms','arms','app_install','calibr')) or n in ('robots','control_modes','org_entitlements','safety_profiles','safety_events'): return 'robotics'
    if n.startswith(('ai_','model_','demonstration','evaluation','dataset','training')): return 'ai'
    return 'other'
dom = collections.defaultdict(list)
for n in sorted(models): dom[domain(n)].append(n)
erd = ['# Logical ERD (generated from `schema.prisma`)', '', f'{len(models)} tables. Only identifiers, foreign keys and status/state columns are drawn; every column is listed in `database-schema.md`. One diagram per domain; cross-domain foreign keys appear as an entity with `FK` attributes only. `classroom_lab_sessions` is released by migration S (not yet in the Production ledger).', '']
for d in ['identity', 'learning', 'robotics', 'ai', 'other']:
    ns = dom.get(d, [])
    if not ns: continue
    erd += [f'## {d.capitalize()} domain ({len(ns)} tables)', '', '```mermaid', 'erDiagram']
    drawn = set(ns); ext = set()
    for n in ns:
        cols, rels = models[n]
        fkcols = {c for _, fks, _ in rels for c in fks}
        erd.append(f'  {n} {{')
        for fname, ftype, pk, uq in cols:
            if pk or fname in fkcols or fname in ('status', 'state', 'code', 'name', 'title', 'email', 'serial_no') or uq:
                tag = 'PK' if pk else ('FK' if fname in fkcols else ('UK' if uq else ''))
                erd.append(f'    {re.sub(r"[^A-Za-z0-9]", "", ftype) or "string"} {fname} {tag}'.rstrip())
        erd.append('  }')
    for n in ns:
        for target, fks, opt in models[n][1]:
            if target in names:
                if target not in drawn: ext.add(target)
                erd.append(f'  {target} {"|o" if opt else "||"}--o{{ {n} : "{",".join(fks)}"')
    for t in sorted(ext): erd.append(f'  {t} {{\n    uuid id PK\n  }}')
    erd += ['```', '']
open(f'{OUT}/generated/erd.md', 'w').write('\n'.join(erd))

# ---------- schema listing + migrations
sch = ['# Database schema (generated from `schema.prisma` and the migration manifest)', '', f'PostgreSQL 17 (hosted Supabase). Schema DDL is owned by the SQL migration runner, not Prisma Migrate. {len(models)} tables.', '']
for d in ['identity', 'learning', 'robotics', 'ai', 'other']:
    for n in dom.get(d, []):
        cols, rels = models[n]
        sch += [f'### `{n}` ({d})', '', '`' + '`, `'.join(f"{c}{' PK' if pk else ''}" for c, _, pk, _ in cols) + '`', '']
mf = json.load(open('database/migrations/manifest.json'))
sch += ['## Release migrations (manifest order)', '', '| # | Version |', '|---|---|'] + [f'| {e["order"]} | `{e["version"]}` |' for e in mf['migrations']] + ['', '## Staged (not in the manifest)', '']
sch += [f'- `{os.path.basename(p)}`' for p in sorted(glob.glob('database/staged-migrations/*.sql'))]
open(f'{OUT}/generated/database-schema.md', 'w').write('\n'.join(sch) + '\n')
print(len(routes), 'routes;', len(models), 'models;', {d: len(v) for d, v in dom.items()})
